"""Build-time extraction of the ORIGINAL figures and reference tables from the team notebook (v2.3).

Usage (from the project root; standard library + Pillow only):
    python tools/extract_notebook_figures.py
    python tools/extract_notebook_figures.py --check      # verify assets against the notebook, write nothing

Source: notebooks/EmiratesPost_Graphs_and_Working.ipynb — the team's "graphs and working" notebook as supplied
(file name as uploaded, without the upload prefix; SHA-256 92cbc029…). It is opened read-only and never modified.

What it does
  * finds every image in code-cell outputs and Markdown/raw-cell attachments; fails clearly if the inventory differs
    from EXPECTED (count, cell, output index, MIME type, pixel size) or an image does not decode;
  * writes each PNG's decoded bytes UNCHANGED to assets/notebook_diagrams/<descriptive name>.png (no resize, crop,
    recolour or format conversion) and checks the written file's SHA-256 against the embedded data — idempotent:
    re-running rewrites identical bytes under the same names and removes nothing else;
  * extracts the notebook's HTML reference tables (DFS trace, Kruskal decisions, Dijkstra trace, coverage, target
    sensitivity, upgrade options, DP traceback, greedy steps, notebook-vs-dashboard summary) to
    assets/notebook_tables/*.csv so the app never parses the notebook at runtime;
  * writes assets/notebook_diagrams/manifest.json (read by src/notebook_diagrams.py) and
    audit/notebook_diagram_inventory.csv.

Classification (visually confirmed for all 11 images): Matplotlib figures generated by the notebook's code — original
team-created notebook figures, NOT photographs or scans of pen-and-paper handwriting.
"""
