class _Tables(HTMLParser):
    """Minimal parser for pandas' to_html output: header rows from <thead>, body rows from <tbody>."""

    def __init__(self):
        super().__init__()
        self.rows, self.cur, self.cell, self.in_cell = [], None, [], False

    def handle_starttag(self, tag, attrs):
        if tag == "tr":
            self.cur = []
        elif tag in ("td", "th"):
            self.in_cell, self.cell = True, []

    def handle_endtag(self, tag):
        if tag in ("td", "th") and self.cur is not None:
            self.cur.append(" ".join("".join(self.cell).split()))
            self.in_cell = False
        elif tag == "tr" and self.cur is not None:
            self.rows.append(self.cur)
            self.cur = None

    def handle_data(self, data):
        if self.in_cell:
            self.cell.append(data)


def html_table(html: str) -> list[list[str]]:
    p = _Tables()
    p.feed(html)
    rows = [r for r in p.rows if any(c != "" for c in r)]
    width = max(len(r) for r in rows)
    rows = [r + [""] * (width - len(r)) for r in rows]
    # pandas writes a named index as a second header row ("Step", "", ...): fold it into the first header cell
    if len(rows) > 1 and rows[1][0] and not any(rows[1][1:]) and not rows[0][0]:
        rows[0][0] = rows[1][0]
        del rows[1]
    # an unnamed default RangeIndex (0, 1, 2, ...) carries no information: drop it
    if not rows[0][0] and [r[0] for r in rows[1:]] == [str(i) for i in range(len(rows) - 1)]:
        rows = [r[1:] for r in rows]
    elif not rows[0][0]:
        rows[0][0] = "Item"
    return rows


def _join(x):
    return x if isinstance(x, str) else "".join(x)


def discover(nb: dict) -> list[dict]:
    found = []
    for ci, cell in enumerate(nb.get("cells", [])):
        for name, att in (cell.get("attachments") or {}).items():
            for mime, data in att.items():
                if mime.startswith("image/"):
                    found.append({"cell": ci, "output": f"attachment:{name}", "mime": mime, "data": _join(data)})
        for oi, out in enumerate(cell.get("outputs") or []):
            for mime, data in (out.get("data") or {}).items():
                if mime.startswith("image/"):
                    found.append({"cell": ci, "output": oi, "mime": mime, "data": _join(data)})
    return found


def build(check_only: bool = False) -> dict:
    raw_nb = NOTEBOOK.read_bytes()
    nb_sha = hashlib.sha256(raw_nb).hexdigest()
    if nb_sha != NOTEBOOK_SHA256:
        raise SystemExit(f"notebook changed or missing: SHA-256 {nb_sha} != expected {NOTEBOOK_SHA256}")
    nb = json.loads(raw_nb)
    found = {(f["cell"], f["output"]): f for f in discover(nb)}
    exp_keys = [(c, o) for c, o, *_ in EXPECTED]
    if sorted(found, key=str) != sorted(exp_keys, key=str):
        raise SystemExit(f"image inventory differs from EXPECTED: found {sorted(found, key=str)}")
    rows = []
    OUT.mkdir(parents=True, exist_ok=True)
    for cell, out, fig, name, panel, size, topic in EXPECTED:
        item = found[(cell, out)]
        if item["mime"] != "image/png":
            raise SystemExit(f"cell {cell} output {out}: expected image/png, found {item['mime']}")
        raw = base64.b64decode(item["data"])
        if not raw:
            raise SystemExit(f"cell {cell} output {out}: empty image data")
        try:
            with Image.open(io.BytesIO(raw)) as im:
                im.verify()
            with Image.open(io.BytesIO(raw)) as im:
                w, h = im.size
        except Exception as e:  # noqa: BLE001
            raise SystemExit(f"cell {cell} output {out}: image does not decode ({e})")
        if (w, h) != size:
            raise SystemExit(f"cell {cell} output {out}: size {w}x{h} != expected {size}")
        sha = hashlib.sha256(raw).hexdigest()
        dest = OUT / f"{name}.png"
        if check_only:
            if not dest.exists() or hashlib.sha256(dest.read_bytes()).hexdigest() != sha:
                raise SystemExit(f"{dest.relative_to(ROOT)} missing or differs from the notebook image")
        else:
            dest.write_bytes(raw)
            assert hashlib.sha256(dest.read_bytes()).hexdigest() == sha
        rows.append({"diagram_id": f"FIG-{fig}", "figure_number": f"Figure {fig}",
                     "descriptive_filename": f"assets/notebook_diagrams/{name}.png",
                     "original_notebook_filename": "EmiratesPost_Graphs_and_Working.ipynb",
                     "notebook_path": str(NOTEBOOK.relative_to(ROOT)), "source_cell_index": cell, "output_index": out,
                     "mime_type": item["mime"], "width_px": w, "height_px": h, "sha256": sha, "algorithm_topic": topic,
                     "assigned_dashboard_panel": PANELS[panel], "panel_key": panel, "classification": CLASSIFICATION,
                     "baseline_scenario": BASELINE,
                     "extraction_status": "extracted; bytes identical to the embedded PNG (no conversion, crop or resize)",
                     "display_test_status": "displayed in Our working; checked by tests/test_notebook_diagrams.py and "
                                            "tools/browser_smoke_test.js"})
    # reference tables
    tables = {}
    TABLES.mkdir(parents=True, exist_ok=True)
    for cell, tname in TABLE_CELLS.items():
        htmls = [_join(o["data"]["text/html"]) for o in nb["cells"][cell].get("outputs", [])
                 if "text/html" in (o.get("data") or {})]
        if not htmls:
            raise SystemExit(f"cell {cell}: expected an HTML table output")
        t = html_table(htmls[-1])
        tables[tname] = {"cell": cell, "rows": len(t) - 1, "file": f"assets/notebook_tables/{tname}.csv"}
        if not check_only:
            with (TABLES / f"{tname}.csv").open("w", newline="", encoding="utf-8") as f:
                csv.writer(f).writerows(t)
    manifest = {"notebook": str(NOTEBOOK.relative_to(ROOT)), "notebook_sha256": nb_sha, "baseline_scenario": BASELINE,
                "classification": CLASSIFICATION, "figures": rows, "tables": tables}
    if not check_only:
        (OUT / "manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        with INVENTORY.open("w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
    return manifest


if __name__ == "__main__":
    m = build(check_only="--check" in sys.argv)
    for r in m["figures"]:
        print(f"  {r['figure_number']:<12} cell {r['source_cell_index']:>2} out {r['output_index']}  "
              f"{r['width_px']}x{r['height_px']}  {r['sha256'][:12]}  -> {r['descriptive_filename']}  [{r['panel_key']}]")
    print(f"{len(m['figures'])} figures and {len(m['tables'])} tables "
          + ("verified against the notebook (no files written)" if "--check" in sys.argv else "extracted"))
